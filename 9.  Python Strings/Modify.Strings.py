# Upper Case
# Example
a = "Hello, World!"
print(a.upper())

# lower Case
# Example
a = "Hello, World!"
print(a.lower())

# Remove Whitespace
# Example
a = " Hello, World! "
print(a.strip()) # returns "Hello, World!"

# Replace String
# Example
a = "Hello, World!"
print(a.replace("H", "J"))

# Split String
# Example
a = "Hello, World!"
print(a.split(",")) # returns ['Hello', ' World!']