# Many Values to Multiple Variables
# Example 1
x, y, z = "Orange", "Banana", "Cherry"
print(x)
print(y)
print(z)

# One Value to Multiple Variables
# Example 1
x = y = z = "Orange"
print(x)
print(y)
print(z)

# Unpack a Collection
# Example 1
fruits = ["apple", "banana", "cherry"]
x, y, z = fruits
print(x)
print(y)
print(z)